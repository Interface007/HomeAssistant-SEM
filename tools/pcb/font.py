def text_strokes(s, x, y, size, anchor="start"):
    """Polylines in mm for `s`, baseline on y. `size` = cap height."""
    s = s.upper()
    scale = size / GLYPH_H
    adv = (GLYPH_W + GLYPH_GAP) * scale
    width = adv * len(s) - GLYPH_GAP * scale if s else 0.0
    if anchor == "middle":
        x -= width / 2
    elif anchor == "end":
        x -= width

    out = []
    for i, ch in enumerate(s):
        glyph = STROKES.get(ch)
        if not glyph:
            continue
        ox = x + i * adv
        for poly in glyph:
            out.append([(ox + px * scale, y + py * scale) for px, py in poly])
    return out
